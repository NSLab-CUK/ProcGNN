"""Export every completed experiment into one paper-ready Excel worksheet.

The source CSVs are produced by ``aggregate_three_server_phase_metrics.py``.
This script performs no experiment discovery or re-evaluation; it only reshapes
the already consolidated summaries, so it is safe and fast to re-run.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from aggregate_three_server_phase_metrics import (
    _build_model_metric_tables,
    _with_macro_stats,
)


EXPERIMENT_LABELS = {
    "single_models": "Phase 1 / 1-S — Single-process",
    "multi_models": "Phase 1 — Multi-process comparison",
    "zero_shot": "Phase 1 — Zero-shot",
    "depth_sensitivity": "Phase 2 — Depth sensitivity",
    "pin_sensitivity": "Phase 2 — PIN sensitivity",
    "data_efficiency": "Phase 3 — Transfer data efficiency",
}


def _tables_for_scope(
    prop: pd.DataFrame,
    summary: pd.DataFrame,
    physics: pd.DataFrame | None,
    scope: str,
) -> list[pd.DataFrame]:
    display = _with_macro_stats(prop, summary)
    tables = _build_model_metric_tables(
        display,
        formatted_mean_std=True,
        physics=physics,
    )
    output: list[pd.DataFrame] = []
    for key, table in tables.items():
        if table.empty:
            continue
        part = table.copy()
        part.insert(0, "Experiment", EXPERIMENT_LABELS[key])
        part.insert(0, "Scope", scope)
        output.append(part)
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--aggregate-dir",
        default="outputs/0819final/three_server_aggregate",
        help="Directory generated by aggregate_three_server_phase_metrics.py",
    )
    parser.add_argument(
        "--output",
        default="outputs/0819final/three_server_aggregate/ALL_EXPERIMENTS_SMAE_MAE_0910.xlsx",
    )
    args = parser.parse_args()
    aggregate = Path(args.aggregate_dir)
    target_prop = pd.read_csv(aggregate / "phase_family_property_summary.csv")
    target_summary = pd.read_csv(aggregate / "phase_family_summary.csv")
    all_prop = pd.read_csv(aggregate / "phase_family_property_summary_all_edges.csv")
    all_summary = pd.read_csv(aggregate / "phase_family_summary_all_edges.csv")
    physics = pd.read_csv(aggregate / "physics_conservation_summary.csv")

    parts = _tables_for_scope(target_prop, target_summary, physics, "Target edge")
    parts += _tables_for_scope(all_prop, all_summary, None, "All edge")
    combined = pd.concat(parts, ignore_index=True)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)

    with pd.ExcelWriter(output, engine="openpyxl") as writer:
        combined.to_excel(writer, sheet_name="all_experiments", index=False)
        sheet = writer.sheets["all_experiments"]
        sheet.freeze_panes = "E2"
        sheet.auto_filter.ref = sheet.dimensions
        widths = {"A": 14, "B": 38, "C": 32, "D": 10, "E": 13}
        for column, width in widths.items():
            sheet.column_dimensions[column].width = width
        for index in range(6, sheet.max_column + 1):
            sheet.column_dimensions[chr(64 + index)].width = 21
    print(f"wrote {output} ({len(combined)} rows)")


if __name__ == "__main__":
    main()
